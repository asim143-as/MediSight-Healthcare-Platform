import os
from datetime import datetime, timezone
from typing import List, Optional, Tuple
from uuid import UUID, uuid4

from fastapi import APIRouter, BackgroundTasks, Depends, File, Form, HTTPException, Query, Request, UploadFile
from pydantic import ValidationError

from . import audit, ocr
from . import supabase as sb
from .auth import CurrentUser, require_roles
from .config import get_settings
from .dbutil import ok_rows, require_patient, write_failed
from .schemas import DownloadOut, ExtractedMeasurement, ReportDetail, ReportOut

router = APIRouter(tags=["reports"])

MAX_BYTES = 10 * 1024 * 1024   # keep in sync with the CHECK on reports.size_bytes
MAX_ROWS = 500                 # cap on measurements accepted from one report

# The first bytes of a file reveal its REAL type. A browser-supplied Content-Type or file
# extension can lie (e.g. a script renamed to .pdf), so we never trust those.
SIGNATURES = [(b"%PDF-", "application/pdf", "pdf"),
              (b"\x89PNG\r\n\x1a\n", "image/png", "png"),
              (b"\xff\xd8\xff", "image/jpeg", "jpg")]

uploaders = require_roles("doctor", "hospital_admin", "patient")
readers = require_roles("doctor", "nurse", "hospital_admin", "super_admin", "patient")

REPORT_COLS = "id,patient_id,original_filename,content_type,size_bytes,status,error_message,created_at,processed_at"
MEASUREMENT_COLS = "id,name,value,unit,measured_at,source_text,ocr_confidence,status,verified_at"


def sniff(data: bytes) -> Optional[Tuple[str, str]]:
    for sig, mime, ext in SIGNATURES:
        if data.startswith(sig):
            return mime, ext
    return None


async def _discard_file(path: str) -> None:
    try:
        await sb.storage_delete(path)
    except Exception:  # best effort cleanup; the original error is what matters
        pass


# ---- OCR hand-off (runs after the upload response has been sent) --------------------------

async def _set_status(report_id: str, status: str, error: Optional[str] = None) -> None:
    body = {"status": status, "error_message": error}
    if status in ("processed", "failed"):
        body["processed_at"] = datetime.now(timezone.utc).isoformat()
    # Service role: users (patients especially) have no UPDATE permission on reports,
    # and processing status is a system fact, not something users should edit.
    await sb.service_request("PATCH", "/rest/v1/reports", params={"id": f"eq.{report_id}"}, json=body)


async def process_report(report_id: str, data: bytes, filename: str, mime: str) -> None:
    # ponytail: FastAPI background task = lost if the server restarts mid-OCR. Use a real
    # queue (and a retry endpoint) if reports must survive restarts.
    try:
        await _set_status(report_id, "processing")
        raw = (await ocr.extract(data, filename, mime))[:MAX_ROWS]
        good, skipped = [], 0
        for item in raw:
            try:
                good.append(ExtractedMeasurement.model_validate(item))
            except ValidationError:
                skipped += 1
        if good:
            rows = [{"report_id": report_id, "name": m.name, "value": m.value, "unit": m.unit,
                     "measured_at": m.measured_at.isoformat() if m.measured_at else None,
                     "source_text": m.source_text, "ocr_confidence": m.confidence} for m in good]
            r = await sb.service_request("POST", "/rest/v1/report_measurements", json=rows)
            if r.status_code >= 400:
                raise RuntimeError("could not save measurements")
        await _set_status(report_id, "processed", f"{skipped} unreadable rows skipped" if skipped else None)
    except Exception:
        # Generic message on purpose: raw upstream errors can leak internals.
        try:
            await _set_status(report_id, "failed", "Report processing failed. Please re-upload the report.")
        except Exception:
            pass


# ---- Endpoints ----------------------------------------------------------------------------

@router.post("/reports", response_model=ReportOut, status_code=201)
async def upload_report(request: Request, background: BackgroundTasks, patient_id: UUID = Form(...),
                        file: UploadFile = File(...), user: CurrentUser = Depends(uploaders)):
    """Upload a PDF/PNG/JPEG report (max 10 MB) for a patient. OCR runs afterwards if connected."""
    audit.note(request, patient_id=str(patient_id))   # the patient is in a form field the middleware can't see
    data = await file.read(MAX_BYTES + 1)          # never read more than the limit + 1 byte
    if len(data) > MAX_BYTES:
        raise HTTPException(413, "File is larger than the 10 MB limit")
    kind = sniff(data)
    if kind is None:
        raise HTTPException(415, "Only PDF, PNG or JPEG files are accepted")
    mime, ext = kind

    pid = str(patient_id)
    await require_patient(pid, user.token)

    # The stored name is generated by us. The user's filename is kept only as display text.
    path = f"{pid}/{uuid4()}.{ext}"
    filename = os.path.basename((file.filename or "report").replace("\\", "/"))[:200] or "report"

    await sb.storage_upload(path, data, mime)
    try:
        # Insert AS THE USER: RLS decides whether they may attach a report to this patient.
        r = await sb.supabase_post("/rest/v1/reports", user.token, {
            "patient_id": pid, "uploaded_by": user.id, "storage_path": path,
            "original_filename": filename, "content_type": mime, "size_bytes": len(data)})
        write_failed(r)
    except Exception:
        await _discard_file(path)                  # don't leave an orphan file behind
        raise
    row = r.json()[0]
    audit.note(request, resource_id=row["id"], details={"content_type": mime, "size_bytes": len(data)})

    if get_settings().ocr_service_url:
        background.add_task(process_report, row["id"], data, filename, mime)
    return row


@router.get("/reports", response_model=List[ReportOut])
async def list_reports(patient_id: UUID = Query(...), user: CurrentUser = Depends(readers)):
    """Reports for one patient, newest first."""
    pid = str(patient_id)
    await require_patient(pid, user.token)
    return ok_rows(await sb.supabase_get("/rest/v1/reports", user.token, {
        "patient_id": f"eq.{pid}", "order": "created_at.desc", "select": REPORT_COLS}))


@router.get("/reports/{report_id}", response_model=ReportDetail)
async def get_report(report_id: UUID, request: Request, user: CurrentUser = Depends(readers)):
    """One report with the values OCR extracted (each marked extracted / verified / rejected)."""
    rows = ok_rows(await sb.supabase_get("/rest/v1/reports", user.token, {
        "id": f"eq.{report_id}", "select": f"{REPORT_COLS},report_measurements({MEASUREMENT_COLS})"}))
    if not rows:
        raise HTTPException(404, "Report not found")
    row = rows[0]
    audit.note(request, patient_id=row["patient_id"])
    row["measurements"] = row.pop("report_measurements", None) or []
    return row


@router.get("/reports/{report_id}/download", response_model=DownloadOut)
async def download_report(report_id: UUID, request: Request, user: CurrentUser = Depends(readers)):
    """A temporary (5 minute) link to the original file. The bucket itself stays private."""
    rows = ok_rows(await sb.supabase_get("/rest/v1/reports", user.token, {
        "id": f"eq.{report_id}", "select": "storage_path,patient_id"}))
    if not rows:                                   # RLS hid it, or it doesn't exist
        raise HTTPException(404, "Report not found")
    audit.note(request, patient_id=rows[0].get("patient_id"))
    return {"url": await sb.storage_signed_url(rows[0]["storage_path"], 300), "expires_in": 300}
